#!/usr/bin/env bash
# validate-adr.sh — ANATOMY / SUBSTANCE FLOOR for a harness ADR. NOT a quality oracle.
#
# This is the mechanical FLOOR: it proves an ADR has the load-bearing anatomy (the sections, >=2
# scored options, a condition-shaped falsifier, reversal, a causal-arrow visual, evidence anchors,
# safe numbering). It CANNOT judge whether the decision is real, well-reasoned, or slop-free — that
# is the JUDGED ceiling (the golden specimen + adversarial review). A green run means "well-formed",
# never "good". Pair it with human/adversarial judgment.
#
# Usage: validate-adr.sh <ADR_FILE | ADR_DIR>
# Exit 0 = all checks PASS; 1 = a floor check FAILED; 2 = bad usage.
set -euo pipefail

TARGET="${1:-}"
[[ -n "$TARGET" ]] || { printf 'usage: validate-adr.sh <ADR_FILE|ADR_DIR>\n' >&2; exit 2; }

if [[ -t 1 && -z "${NO_COLOR:-}" ]]; then R=$'\033[0;31m'; G=$'\033[0;32m'; X=$'\033[0m'; else R=''; G=''; X=''; fi
fails=0
_pass() { printf '  %sPASS%s  %s\n' "$G" "$X" "$1"; }
_fail() { printf '  %sFAIL%s  %s\n' "$R" "$X" "$1"; fails=$((fails + 1)); }

_require_section() {
  local file="$1" heading="$2"
  if grep -qE "^#{1,4} +${heading}" "$file"; then _pass "section: ${heading}"; else _fail "missing section: ${heading}"; fi
}

_validate_file() {
  local file="$1" base opts anchors
  base="$(basename -- "$file")"
  printf '%s\n' "ADR: $base"

  # 1. Frontmatter + required fields + status enum
  if [[ "$(head -1 "$file")" == "---" ]]; then _pass "frontmatter fence"; else _fail "missing frontmatter (--- on line 1)"; fi
  local fm; fm="$(awk 'NR>1 && /^---[[:space:]]*$/{exit} NR>1{print}' "$file")"
  local f
  for f in id title status date; do
    if printf '%s\n' "$fm" | grep -qE "^${f}:"; then _pass "field: ${f}"; else _fail "missing frontmatter field: ${f}"; fi
  done
  local st; st="$(printf '%s\n' "$fm" | grep -E '^status:' | head -1 | sed 's/^status:[[:space:]]*//' | tr -d '[:space:]')"
  case "$st" in
    proposed|accepted|superseded|deprecated) _pass "status enum: ${st}" ;;
    *) _fail "invalid status '${st}' (proposed|accepted|superseded|deprecated)" ;;
  esac

  # 2. Required sections (the 4 asserted + Consequences)
  _require_section "$file" "Context and Problem Statement"
  _require_section "$file" "Decision Drivers"
  _require_section "$file" "Considered Options"
  _require_section "$file" "Decision Outcome"
  _require_section "$file" "Consequences"

  # 3. >=2 scored options
  opts="$(grep -cE '^\s*[0-9]+\.\s+\*\*Option|^#{2,4} +Option|\*\*Option [A-Z0-9]' "$file" || true)"
  if (( opts >= 2 )); then _pass ">=2 options (${opts})"; else _fail "fewer than 2 options (${opts}) — no decision to defend"; fi

  # 4. Condition-shaped falsifier (present AND not outcome-shaped)
  if grep -qi 'Falsifier' "$file"; then
    _pass "falsifier present"
    # Outcome-shaped check (robust to colon/period/bold markers): among lines that mention a
    # falsifier, does any use an outcome phrase instead of a pre-flightable condition?
    if grep -i 'falsifier' "$file" | grep -iE 'if it fails|if it does ?n.?t work|when it breaks|if it breaks' >/dev/null; then
      _fail "outcome-shaped falsifier ('if it fails') — must be a pre-flightable CONDITION"
    else
      _pass "falsifier is condition-shaped"
    fi
  else
    _fail "no falsifier — each option needs a pre-flightable failure condition"
  fi

  # 5. Reversal cost documented
  if grep -qiE 'reversal|rollback|undo' "$file"; then _pass "reversal documented"; else _fail "no reversal/rollback cost"; fi

  # 6. Causal-arrow visual (machine-checked visual #1 of 2)
  if grep -qE '→|↓' "$file"; then _pass "causal-arrow visual"; else _fail "no causal-chain arrow (→/↓)"; fi

  # 6b. Mermaid FENCE present (crown heuristic 4). Content-blind: an empty/label-only block PASSES this floor;
  #     per-option mechanism coverage + "shows mechanism, not label" are the JUDGED bar (specimen + review).
  if grep -qE '^[[:space:]]*```mermaid' "$file"; then _pass "mermaid diagram present"; else _fail "no \`\`\`mermaid diagram — options/decision need a rendered mechanism diagram (crown heuristic 4)"; fi

  # 7. Evidence anchors (floor: >=2 of [per: …] / file:line)
  anchors="$(grep -oE '\[per:|[A-Za-z0-9_./-]+\.(sh|md|tf|ts|tsx|js|py|ya?ml|json|tmpl):[0-9]+' "$file" | wc -l | tr -d ' ')"
  if (( anchors >= 2 )); then _pass "evidence anchors (${anchors})"; else _fail "too few evidence anchors (${anchors}) — claims need [per:]/file:line"; fi

  # 8. Append-only marker: not auto-generated (ADRs are author-owned, never overwritten)
  if grep -q '<!-- Auto-generated by codebase-harness' "$file"; then
    _fail "ADR carries the auto-generated marker — ADRs are author-owned, never machine-regenerated"
  else
    _pass "not auto-generated (author-owned)"
  fi
}

# Duplicate NNNN-prefix check across the ledger directory (catches id collisions, incl. 0000 seed clashes).
_check_dup_prefixes() {
  local dir="$1" f base dups
  dups="$(
    for f in "$dir"/[0-9][0-9][0-9][0-9]-*.md; do
      [[ -e "$f" ]] || continue
      base="$(basename -- "$f")"
      printf '%s\n' "${base:0:4}"
    done | sort | uniq -d
  )"
  if [[ -n "$dups" ]]; then
    _fail "duplicate ADR id prefix(es) in ${dir}: $(printf '%s' "$dups" | tr '\n' ' ')"
  else
    _pass "no duplicate id prefixes in ${dir}"
  fi
}

if [[ -d "$TARGET" ]]; then
  _check_dup_prefixes "$TARGET"
  shopt -s nullglob 2>/dev/null || true
  for f in "$TARGET"/[0-9][0-9][0-9][0-9]-*.md; do _validate_file "$f"; done
elif [[ -f "$TARGET" ]]; then
  _validate_file "$TARGET"
  _check_dup_prefixes "$(dirname -- "$TARGET")"
else
  printf 'not found: %s\n' "$TARGET" >&2; exit 2
fi

if (( fails > 0 )); then
  printf '\n%sFLOOR FAILED%s: %d check(s). Anatomy floor only — a PASS is "well-formed", not "good".\n' "$R" "$X" "$fails" >&2
  exit 1
fi
printf '\n%sFLOOR PASSED%s (anatomy only — judge quality against the golden specimen + adversarial review).\n' "$G" "$X"
